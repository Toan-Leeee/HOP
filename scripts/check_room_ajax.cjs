const { chromium } = require('playwright');
const fs = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');
const base = process.env.MEETING_URL || 'http://localhost:5092';
const output = path.resolve('Nop_ca_nhan_Le_Xuan_Toan/Ajax_Room/Minh_chung');
(async () => {
    await fs.mkdir(output, { recursive: true });
    const browser = await chromium.launch({ channel: 'msedge', headless: true });
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    const page = await context.newPage();
    page.setDefaultTimeout(12000);
    const checks = [], errors = [];
    let documents = 0;
    page.on('pageerror', e => errors.push(e.message));
    page.on('console', m => console.log('BROWSER', m.text()));
    page.on('request', r => { if (r.isNavigationRequest() && r.frame() === page.mainFrame()) documents++; });
    const check = (condition, name) => { assert.ok(condition, name); checks.push(name); console.log(name); };
    const shot = name => page.screenshot({ path: path.join(output, name + '.png'), fullPage: true, animations: 'disabled' });
    const waitList = action => Promise.all([page.waitForResponse(r => r.url().includes('/ListJson') && r.status() === 200), action()]);
    const settle = () => page.locator('#room-table-wrap[aria-busy="false"]').waitFor();
    const login = async email => {
        await page.goto(base + '/Account/Login');
        await page.locator('[name=Email]').fill(email);
        await page.locator('[name=Password]').fill('Demo@12345');
        await Promise.all([page.waitForURL(u => !u.pathname.includes('Login')), page.locator('button[type=submit]').click()]);
    };
    try {
        await login('admin@company.test');
        await page.goto(base + '/Admin/Room');
        await settle();
        const initialDocuments = documents;
        check(await page.locator('#room-rows tr').count() > 0, 'XMLHttpRequest renders room table');
        await shot('01_Danh_sach_Ajax');
        const token = await page.locator('#room-editor [name=__RequestVerificationToken]').inputValue();
        const noToken = await context.request.post(base + '/Admin/Room/SaveJson', { form: { RoomName: 'Rejected', Capacity: '10', Status: 'Active' } });
        check(noToken.status() === 400, 'Antiforgery rejects missing token');
        const invalid = await context.request.post(base + '/Admin/Room/SaveJson', { form: { __RequestVerificationToken: token, RoomName: 'Invalid', Capacity: '0', Status: 'Active' } });
        check(invalid.status() === 400 && !!(await invalid.json()).errors, 'Server validates capacity');
        const invalidFilter = await context.request.get(base + '/Admin/Room/ListJson?Page=invalid');
        check(invalidFilter.status() === 400, 'Invalid filter returns JSON error');
        const evil = '<img src=x onerror=alert(1)>';
        const names = ['AJAX Toan Demo ' + Date.now(), ...['02', '03', '04', '05'].map(n => 'AJAX ' + n + ' ' + Date.now()), evil + Date.now()];
        for (const name of names) {
            const r = await context.request.post(base + '/Admin/Room/SaveJson', { form: { __RequestVerificationToken: token, RoomName: name, Capacity: '15', Status: 'Active' } });
            check(r.ok(), 'Create JSON ' + name);
        }
        await waitList(() => page.locator('#search').fill('AJAX'));
        await settle();
        check((await page.locator('#room-rows').innerText()).includes('AJAX'), 'fetch search updates DOM');
        await shot('02_Fetch_Tim_kiem');
        await waitList(() => page.locator('#pageSize').selectOption('5'));
        await settle();
        await waitList(() => page.locator('#room-reset').click());
        await settle();
        await waitList(() => page.locator('#pageSize').selectOption('5'));
        await settle();
        check(await page.locator('#room-rows img').count() === 0, 'Stored HTML rendered as text, no XSS markup');
        await waitList(() => page.locator('#room-next').click());
        await settle();
        check((await page.locator('#room-page').innerText()).includes('Trang 2'), 'XHR pagination loads page 2');
        await shot('03_Phan_trang');
        await page.locator('#room-add').click();
        const demoName = 'Phong Ajax Toan ' + Date.now();
        await page.locator('#room-name').fill(demoName);
        await page.locator('#room-location').fill('Tang 3 - Khu A');
        await page.locator('#room-capacity').fill('24');
        await page.locator('#room-equipment').fill('May chieu, bang viet, hoi nghi truc tuyen');
        await shot('04_Them_phong');
        const saveResponse = page.waitForResponse(r => r.url().includes('/SaveJson'));
        await page.locator('#room-save').click();
        check((await saveResponse).ok(), 'jQuery AJAX creates room');
        await page.locator('#room-modal').waitFor({ state: 'hidden' });
        await settle();
        await waitList(() => page.locator('#search').fill(demoName));
        await settle();
        await shot('05_Ket_qua_them');
        await page.locator('[data-action=edit]').click();
        await page.locator('#room-capacity').fill('30');
        await page.locator('#room-status').selectOption('Maintenance');
        await shot('06_Sua_bao_tri');
        await waitList(() => page.locator('#room-save').click());
        await settle();
        await page.locator('#room-modal').waitFor({ state: 'hidden' });
        check((await page.locator('#room-rows').innerText()).includes('30 người'), 'AJAX edit updates capacity');
        check((await page.locator('#room-rows').innerText()).includes('Bảo trì'), 'AJAX edit updates maintenance');
        await page.locator('#room-add').click();
        await page.locator('#room-name').fill(demoName);
        await page.locator('#room-capacity').fill('20');
        await page.locator('#room-save').click();
        await page.locator('#room-errors:not([hidden])').waitFor();
        check((await page.locator('#room-errors').innerText()).includes('đã tồn tại'), 'Duplicate name shown in modal');
        await shot('07_Validation_trung_ten');
        await page.locator('#room-modal .modal-header .btn-close').click();
        await page.locator('#room-modal').waitFor({ state: 'hidden' });
        page.once('dialog', d => d.accept());
        await waitList(() => page.locator('[data-action=disable]').click());
        await settle();
        check((await page.locator('#room-rows').innerText()).includes('Không có'), 'jQuery soft delete removes active row');
        await waitList(() => page.locator('#disabled').selectOption('true'));
        await settle();
        check(await page.locator('[data-action=restore]').count() === 1, 'Disabled room retained and restorable');
        await shot('08_Ngung_su_dung');
        page.once('dialog', d => d.accept());
        await waitList(() => page.locator('[data-action=restore]').click());
        await settle();
        await waitList(() => page.locator('#disabled').selectOption('false'));
        await settle();
        check(await page.locator('[data-action=edit]').count() === 1, 'Restore returns room to active list');
        await shot('09_Khoi_phuc');
        check(documents === initialDocuments, 'Search CRUD and pagination do not navigate/reload document');
        await page.setViewportSize({ width: 390, height: 844 });
        await shot('10_Mobile');
        check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Mobile page has no horizontal overflow');
        const last = await context.request.get(base + '/Admin/Room/ListJson?Page=999999&PageSize=5');
        const lastData = await last.json();
        check(lastData.page <= Math.max(1, lastData.totalPages), 'Out of range page clamped');
        await context.clearCookies();
        await login('employee@company.test');
        const forbidden = await context.request.get(base + '/Admin/Room/ListJson');
        check(forbidden.status() === 403, 'Employee denied Admin JSON endpoint');
        check(errors.length === 0, 'No JavaScript errors');
    } catch (error) {
        console.error(error, errors);
        await shot('ERROR');
        throw error;
    } finally {
        await fs.writeFile(path.join(output, 'ket_qua_kiem_tra.json'), JSON.stringify({ base, checks, errors }, null, 2));
        await context.close();
        await browser.close();
        console.log(JSON.stringify({ passed: checks.length, checks, errors }, null, 2));
    }
})().catch(e => { console.error(e); process.exitCode = 1; });
